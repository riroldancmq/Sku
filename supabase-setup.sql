-- 1) TABLAS
create table if not exists public.products (
  id bigint generated always as identity primary key,
  sku text,
  "desc" text,
  pisos integer,
  packs_piso integer,
  packs_paleta integer,
  created_at timestamptz default now()
);

create table if not exists public.filter_groups (
  id bigint generated always as identity primary key,
  label text not null,
  color text,
  sort_order integer default 0
);

create table if not exists public.filter_brands (
  id bigint generated always as identity primary key,
  group_id bigint not null references public.filter_groups(id) on delete cascade,
  label text,
  key text,
  sort_order integer default 0
);

-- 2) SEGURIDAD: lectura pública anónima, escritura solo autenticados
alter table public.products enable row level security;
alter table public.filter_groups enable row level security;
alter table public.filter_brands enable row level security;

drop policy if exists "lectura_publica" on public.products;
create policy "lectura_publica" on public.products for select using (true);
drop policy if exists "admin_escritura" on public.products;
create policy "admin_escritura" on public.products for all to authenticated using (true) with check (true);
drop policy if exists "lectura_publica" on public.filter_groups;
create policy "lectura_publica" on public.filter_groups for select using (true);
drop policy if exists "admin_escritura" on public.filter_groups;
create policy "admin_escritura" on public.filter_groups for all to authenticated using (true) with check (true);
drop policy if exists "lectura_publica" on public.filter_brands;
create policy "lectura_publica" on public.filter_brands for select using (true);
drop policy if exists "admin_escritura" on public.filter_brands;
create policy "admin_escritura" on public.filter_brands for all to authenticated using (true) with check (true);

